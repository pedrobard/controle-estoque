
CREATE TABLE public.administradores (
    id_administrador integer
        GENERATED BY DEFAULT AS IDENTITY,

    nome_usuario varchar(30) NOT NULL,

    senha_hash text NOT NULL,

    segredo_totp_cifrado text,

    totp_configurado boolean
        DEFAULT false NOT NULL,

    criado_em timestamp without time zone
        DEFAULT CURRENT_TIMESTAMP NOT NULL,

    atualizado_em timestamp without time zone
        DEFAULT CURRENT_TIMESTAMP NOT NULL,

    CONSTRAINT administradores_pkey
        PRIMARY KEY (id_administrador),

    CONSTRAINT uq_administradores_nome_usuario
        UNIQUE (nome_usuario),

    CONSTRAINT ck_administradores_nome_usuario
        CHECK ( nome_usuario = LOWER(BTRIM(nome_usuario)) AND nome_usuario ~ '^[a-z0-9._-]{4,30}$')
);


CREATE UNIQUE INDEX uq_administradores_unico_registro
ON public.administradores ((true));



